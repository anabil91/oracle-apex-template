create table customers (
   customer_id    number generated by default on null as identity
                  constraint customers_pk primary key,
   full_name      varchar2(200 char)  not null,
   email          varchar2(320 char)  not null
                  constraint customers_email_uk unique,
   status         varchar2(10 char)   default 'ACTIVE' not null
                  constraint customers_status_ck check (status in ('ACTIVE', 'INACTIVE')),
   created_on     timestamp with local time zone default systimestamp not null,
   created_by     varchar2(255 char)  default coalesce(sys_context('APEX$SESSION', 'APP_USER'), user) not null
);
